'use strict';
// Generates js/countries.js: country names from Unicode CLDR (the data in Node's ICU) in every
// interface language, because webOS TV 4.x (Chromium 53) has no Intl.DisplayNames.
// Usage: node tools/countries.js

const fs = require('fs');
const path = require('path');
const I18N = require('../js/i18n.js');

const A = 'A'.charCodeAt(0);
const codes = [];
for (let i = 0; i < 26; i++) for (let j = 0; j < 26; j++) codes.push(String.fromCharCode(A + i, A + j));

const names = {};
for (const lang of I18N.languages) {
  const d = new Intl.DisplayNames([lang], { type: 'region', fallback: 'none' });
  names[lang] = {};
  for (const c of codes) { const n = d.of(c); if (n && n !== c) names[lang][c] = n; }
}

const out = '// Generated by tools/countries.js from Unicode CLDR ' + process.versions.cldr +
  ' (Unicode License v3, licenses/CLDR-LICENSE.txt). Do not edit.\n' +
  'var COUNTRY_NAMES = ' + JSON.stringify(names) + ';\n' +
  "if (typeof module !== 'undefined' && module.exports) module.exports = COUNTRY_NAMES;\n";
fs.writeFileSync(path.join(__dirname, '..', 'js', 'countries.js'), out);
console.log('countries: ' + Object.keys(names.en).length + ' regions × ' + I18N.languages.length + ' languages');
