'use strict';
// Generates the Android launcher icon from img/icon.svg: adaptive layers (background and foreground,
// Android 8+), the themed-icon layer from img/icon-monochrome.svg (Android 13+), the legacy icon and
// the logo the app draws in its own screens. Needs rsvg-convert (librsvg).
// Usage: node tools/android-icon.js

const fs = require('fs');
const os = require('os');
const path = require('path');
const { execFileSync } = require('child_process');

const ROOT = path.join(__dirname, '..');
const RES = path.join(ROOT, 'android', 'app', 'src', 'main', 'res');
const DENSITY = { mdpi: 1, hdpi: 1.5, xhdpi: 2, xxhdpi: 3, xxxhdpi: 4 };

const svg = fs.readFileSync(path.join(ROOT, 'img', 'icon.svg'), 'utf8');
const defs = svg.slice(svg.indexOf('<defs>'), svg.indexOf('</defs>') + 7);
const body = svg.slice(svg.indexOf('<g clip-path="url(#shape)">') + 27, svg.lastIndexOf('</g>'));
const BG = '<rect width="1024" height="1024" fill="url(#bg)"/>\n    <rect width="1024" height="1024" fill="url(#tvLight)"/>';
const SHINE = body.slice(body.indexOf('<!-- Glass highlight'));
if (!body.includes(BG) || !SHINE) throw new Error('icon.svg changed: update tools/android-icon.js');

// The 1024 artwork fills 80 of the 108 dp layer, so the launcher's 72 dp mask trims only its outer 5%.
const PAD = 1024 * (108 / 80 - 1) / 2;
const box = 'viewBox="' + -PAD + ' ' + -PAD + ' ' + (1024 + 2 * PAD) + ' ' + (1024 + 2 * PAD) + '"';
const layer = (inner) => '<svg xmlns="http://www.w3.org/2000/svg" ' + box + '>' + defs + inner + '</svg>';
const background = layer('<rect x="' + -PAD + '" y="' + -PAD + '" width="' + (1024 + 2 * PAD) + '" height="' + (1024 + 2 * PAD) + '" fill="url(#bg)"/>' +
  '<rect x="' + -PAD + '" y="' + -PAD + '" width="' + (1024 + 2 * PAD) + '" height="' + (1024 + 2 * PAD) + '" fill="url(#tvLight)"/>');
const foreground = layer(body.replace(BG, '').replace(SHINE, ''));

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'mommytv-icon-'));
const render = (source, px, out) => {
  const file = path.join(tmp, 'layer.svg');
  fs.writeFileSync(file, source);
  fs.mkdirSync(path.dirname(out), { recursive: true });
  execFileSync('rsvg-convert', ['-w', String(px), '-h', String(px), file, '-o', out]);
};

const mono = fs.readFileSync(path.join(ROOT, 'img', 'icon-monochrome.svg'), 'utf8');
for (const [name, scale] of Object.entries(DENSITY)) {
  const dir = path.join(RES, 'mipmap-' + name);
  render(background, 108 * scale, path.join(dir, 'ic_launcher_background.png'));
  render(foreground, 108 * scale, path.join(dir, 'ic_launcher_foreground.png'));
  render(mono, 108 * scale, path.join(dir, 'ic_launcher_monochrome.png'));
  render(svg, 48 * scale, path.join(dir, 'ic_launcher.png')); // Android 7 and older
}
render(svg, 512, path.join(RES, 'drawable-nodpi', 'logo.png')); // in-app logo: Compose cannot draw adaptive icons

fs.mkdirSync(path.join(RES, 'mipmap-anydpi-v26'), { recursive: true });
fs.writeFileSync(path.join(RES, 'mipmap-anydpi-v26', 'ic_launcher.xml'),
  '<?xml version="1.0" encoding="utf-8"?>\n' +
  '<!-- Generated by tools/android-icon.js from img/icon.svg. Do not edit by hand. -->\n' +
  '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n' +
  '    <background android:drawable="@mipmap/ic_launcher_background" />\n' +
  '    <foreground android:drawable="@mipmap/ic_launcher_foreground" />\n' +
  '    <monochrome android:drawable="@mipmap/ic_launcher_monochrome" />\n' +
  '</adaptive-icon>\n');
fs.rmSync(tmp, { recursive: true });
console.log('android icon: adaptive, themed, legacy and in-app logo written');
