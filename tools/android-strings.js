'use strict';
// Generates the Android string resources from js/i18n.js, so every platform shows the same texts.
// Usage: node tools/android-strings.js   (writes android/app/src/main/res/values*/strings.xml)

const fs = require('fs');
const path = require('path');
const I18N = require('../js/i18n.js');

const RES = path.join(__dirname, '..', 'android', 'app', 'src', 'main', 'res');
const FOLDER = { en: 'values', es: 'values-es', fr: 'values-fr', de: 'values-de', it: 'values-it', pt: 'values-pt', zh: 'values-zh', ja: 'values-ja' };

function escape(s) {
  let n = 0;
  return String(s)
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
    .replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/"/g, '\\"')
    .replace(/\{(\d)\}/g, (m, i) => { n++; return '%' + (Number(i) + 1) + '$s'; })
    .replace(/^@/, '\\@').replace(/^\?/, '\\?');
}

for (const lang of I18N.languages) {
  const dict = I18N.dicts[lang];
  // Some strings are used only by the webOS app; both apps share js/i18n.js, so lint's UnusedResources is expected here.
  const lines = ['<?xml version="1.0" encoding="utf-8"?>', '<!-- Generated by tools/android-strings.js from js/i18n.js. Do not edit by hand. -->',
    '<resources xmlns:tools="http://schemas.android.com/tools" tools:ignore="UnusedResources">'];
  if (lang === 'en') lines.push('    <string name="app_name" translatable="false">MommyTV</string>');
  for (const key of Object.keys(dict)) {
    if (typeof dict[key] !== 'string' || key === 'date') continue;
    const formatted = /\{\d\}/.test(dict[key]) ? '' : ' formatted="false"';
    lines.push('    <string name="' + key + '"' + formatted + '>' + escape(dict[key]) + '</string>');
  }
  // iptv-org categories: the ids once (untranslatable) and their names in this language, in the same order
  const catIds = Object.keys(I18N.categoryNames.en);
  const item = (s) => '        <item>' + escape(s) + '</item>';
  if (lang === 'en') lines.push('    <string-array name="categoryKeys" translatable="false">', ...catIds.map(item), '    </string-array>');
  lines.push('    <string-array name="categoryNames">', ...catIds.map((id) => item(I18N.categoryNames[lang][id])), '    </string-array>');
  lines.push('</resources>', '');
  const dir = path.join(RES, FOLDER[lang]);
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'strings.xml'), lines.join('\n'));
  console.log('written', FOLDER[lang] + '/strings.xml', Object.keys(dict).length);
}
